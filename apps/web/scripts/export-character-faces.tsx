/**
 * Draws every character with the web app's own <Character> component and
 * writes the SVGs for the mobile app, which renders them with
 * react-native-svg. One drawing, two apps: run this after changing a
 * character.
 *
 *   pnpm --filter @binary/web faces:export
 */
import {writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

import {CHARACTER_IDS} from '@binary/shared';
import {renderToStaticMarkup} from 'react-dom/server';

import {Character, type Mood} from '../src/components/characters/character';

const MOODS: Mood[] = ['idle', 'thinking', 'talking', 'happy', 'oops'];
const OUTPUT = fileURLToPath(
  new URL('../../mobile/src/lib/character-faces.ts', import.meta.url),
);

/**
 * Static SVG: no classes (they only animate on the web), and no fixed size
 * on the outer <svg>, which the app sizes itself.
 */
function svgOf(element: React.ReactElement) {
  return renderToStaticMarkup(element)
    .replace(/ class="[^"]*"/g, '')
    .replace(/^<svg[^>]*>/, (tag) =>
      tag.replace(/ (width|height|aria-hidden|data-mood)="[^"]*"/g, ''),
    );
}

const drawings = Object.fromEntries(
  CHARACTER_IDS.map((id) => [
    id,
    {
      full: svgOf(<Character id={id} />),
      face: Object.fromEntries(
        MOODS.map((mood) => [
          mood,
          svgOf(<Character id={id} mood={mood} variant="face" />),
        ]),
      ),
    },
  ]),
);

writeFileSync(
  OUTPUT,
  `// Generated by apps/web/scripts/export-character-faces.tsx. Do not edit.
import type {CharacterId} from '@binary/shared';

export type Mood = ${MOODS.map((mood) => `'${mood}'`).join(' | ')};

/** Each character's full drawing and its face in every mood, as SVG. */
export const CHARACTER_SVGS: Record<
  CharacterId,
  {full: string; face: Record<Mood, string>}
> = ${JSON.stringify(drawings, null, 2)};
`,
);
console.log(`Wrote ${OUTPUT}`);
